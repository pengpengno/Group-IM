CREATE TABLE wb_approval_definition (
    definition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    form_schema_json TEXT NOT NULL DEFAULT '{}',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    definition_version INTEGER NOT NULL DEFAULT 1,
    created_by BIGINT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE wb_approval_instance (
    instance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_id BIGINT NOT NULL,
    definition_version INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL,
    applicant_id BIGINT NOT NULL,
    department_id BIGINT,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    form_data_json TEXT NOT NULL DEFAULT '{}',
    current_node_order INTEGER,
    submitted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wb_approval_instance_definition FOREIGN KEY (definition_id) REFERENCES wb_approval_definition(definition_id),
    CONSTRAINT wb_approval_instance_status_check CHECK (status IN ('DRAFT','PENDING','APPROVED','REJECTED','RETURNED','CANCELLED'))
);
CREATE INDEX idx_wb_approval_instance_applicant_created ON wb_approval_instance(applicant_id, created_at DESC);
CREATE INDEX idx_wb_approval_instance_status_created ON wb_approval_instance(status, created_at DESC);

CREATE TABLE wb_approval_node (
    node_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id BIGINT NOT NULL,
    node_order INTEGER NOT NULL,
    assignee_id BIGINT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'WAITING',
    started_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wb_approval_node_instance FOREIGN KEY (instance_id) REFERENCES wb_approval_instance(instance_id) ON DELETE CASCADE,
    CONSTRAINT uk_wb_approval_node_order UNIQUE (instance_id, node_order),
    CONSTRAINT wb_approval_node_status_check CHECK (status IN ('WAITING','PENDING','APPROVED','REJECTED','RETURNED','CANCELLED'))
);
CREATE INDEX idx_wb_approval_node_assignee_status ON wb_approval_node(assignee_id, status);

CREATE TABLE wb_approval_action (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id BIGINT NOT NULL,
    node_id BIGINT,
    operator_id BIGINT NOT NULL,
    action VARCHAR(24) NOT NULL,
    comment TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wb_approval_action_instance FOREIGN KEY (instance_id) REFERENCES wb_approval_instance(instance_id) ON DELETE CASCADE,
    CONSTRAINT fk_wb_approval_action_node FOREIGN KEY (node_id) REFERENCES wb_approval_node(node_id) ON DELETE SET NULL,
    CONSTRAINT wb_approval_action_check CHECK (action IN ('SUBMIT','APPROVE','REJECT','RETURN','RESUBMIT','CANCEL'))
);
CREATE INDEX idx_wb_approval_action_instance_created ON wb_approval_action(instance_id, created_at);

CREATE TABLE wb_approval_cc (
    cc_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    delivered_at TIMESTAMP(6) WITHOUT TIME ZONE,
    read_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wb_approval_cc_instance FOREIGN KEY (instance_id) REFERENCES wb_approval_instance(instance_id) ON DELETE CASCADE,
    CONSTRAINT uk_wb_approval_cc UNIQUE (instance_id, user_id)
);
CREATE INDEX idx_wb_approval_cc_user_read ON wb_approval_cc(user_id, read_at);

