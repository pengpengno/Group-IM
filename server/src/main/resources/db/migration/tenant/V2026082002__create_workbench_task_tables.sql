-- Workbench Task V1. Tenant schema is the company boundary, so wb_* rows do
-- not repeat company_id. User/department/conversation references are IDs on
-- purpose; Workbench domain services validate them through platform adapters.

CREATE TABLE wb_task (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'TODO',
    priority VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    creator_id BIGINT NOT NULL,
    owner_id BIGINT,
    department_id BIGINT,
    source_type VARCHAR(32),
    source_id VARCHAR(100),
    conversation_id BIGINT,
    start_at TIMESTAMP(6) WITHOUT TIME ZONE,
    due_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    progress INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT wb_task_status_check CHECK (status IN ('TODO', 'IN_PROGRESS', 'BLOCKED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT wb_task_priority_check CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT wb_task_progress_check CHECK (progress BETWEEN 0 AND 100)
);

CREATE INDEX idx_wb_task_owner_status ON wb_task(owner_id, status);
CREATE INDEX idx_wb_task_creator_created ON wb_task(creator_id, created_at DESC);
CREATE INDEX idx_wb_task_due_status ON wb_task(due_at, status);
CREATE INDEX idx_wb_task_department_status ON wb_task(department_id, status);
CREATE INDEX idx_wb_task_conversation ON wb_task(conversation_id);

CREATE TABLE wb_task_assignee (
    assignee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wb_task_assignee_task FOREIGN KEY (task_id) REFERENCES wb_task(task_id) ON DELETE CASCADE,
    CONSTRAINT wb_task_assignee_role_check CHECK (role IN ('OWNER', 'COLLABORATOR', 'WATCHER')),
    CONSTRAINT uk_wb_task_assignee UNIQUE (task_id, user_id, role)
);

CREATE INDEX idx_wb_task_assignee_user_task ON wb_task_assignee(user_id, task_id);
CREATE INDEX idx_wb_task_assignee_task ON wb_task_assignee(task_id);

CREATE TABLE wb_task_comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    reply_to_id BIGINT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_wb_task_comment_task FOREIGN KEY (task_id) REFERENCES wb_task(task_id) ON DELETE CASCADE,
    CONSTRAINT fk_wb_task_comment_reply FOREIGN KEY (reply_to_id) REFERENCES wb_task_comment(comment_id) ON DELETE SET NULL,
    CONSTRAINT wb_task_comment_content_check CHECK (length(btrim(content)) > 0)
);

CREATE INDEX idx_wb_task_comment_task_created ON wb_task_comment(task_id, created_at);

CREATE TABLE wb_task_activity (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    before_state VARCHAR(32),
    after_state VARCHAR(32),
    detail TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_wb_task_activity_task FOREIGN KEY (task_id) REFERENCES wb_task(task_id) ON DELETE CASCADE,
    CONSTRAINT wb_task_activity_action_check CHECK (action IN (
        'CREATE', 'UPDATE', 'ASSIGN', 'UNASSIGN', 'START', 'BLOCK', 'RESUME',
        'COMPLETE', 'REOPEN', 'CANCEL', 'UPDATE_DUE_AT', 'UPDATE_PRIORITY',
        'UPDATE_PROGRESS', 'COMMENT', 'ATTACH_FILE'
    ))
);

CREATE INDEX idx_wb_task_activity_task_created ON wb_task_activity(task_id, created_at);
