-- Core tenant baseline: automation, bot, conversation and department tables.
-- Schema-relative; global identity remains in public.*.

CREATE TABLE "approval_requests" (
    "approval_id" bigint NOT NULL,
    "created_at" timestamp(6) without time zone,
    "decided_at" timestamp(6) without time zone,
    "expires_at" timestamp(6) without time zone NOT NULL,
    "status" character varying(32) NOT NULL,
    "execution_id" bigint NOT NULL,
    "requested_by_user_id" bigint NOT NULL,
    CONSTRAINT "approval_requests_status_check" CHECK ((("status")::"text" = ANY ((ARRAY['PENDING'::character varying, 'APPROVED'::character varying, 'DECLINED'::character varying])::"text"[])))
);

ALTER TABLE "approval_requests" ALTER COLUMN "approval_id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "approval_requests_approval_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

