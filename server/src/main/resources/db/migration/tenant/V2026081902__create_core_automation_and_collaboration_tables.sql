    "requested_by_user_id" bigint NOT NULL,
    "rule_id" bigint,
    CONSTRAINT "automation_executions_status_check" CHECK ((("status")::"text" = ANY ((ARRAY['PENDING_APPROVAL'::character varying, 'APPROVED'::character varying, 'DECLINED'::character varying, 'EXECUTED'::character varying, 'FAILED'::character varying])::"text"[])))
);

ALTER TABLE "automation_executions" ALTER COLUMN "execution_id" ADD GENERATED BY DEFAULT AS IDENTITY (
